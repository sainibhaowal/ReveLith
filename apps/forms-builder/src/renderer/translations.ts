export type BuiltInLocale = keyof typeof BUILT_IN_LOCALES
export type RespondentMessage = keyof typeof BUILT_IN_LOCALES.en
export function resolveLocale(locale?: string): string {
  if (!locale) return 'en'
  try {
    return Intl.getCanonicalLocales(locale)[0] ?? 'en'
  } catch {
    return 'en'
  }
}
export function respondentMessage(
  locale: string | undefined,
  key: RespondentMessage,
  values: Record<string, string | number> = {},
): string {
  const canonical = resolveLocale(locale)
  const language = canonical.split('-')[0] as BuiltInLocale
  const catalog = BUILT_IN_LOCALES[language] ?? BUILT_IN_LOCALES.en
  let message: string = catalog[key] ?? BUILT_IN_LOCALES.en[key]
  for (const [name, value] of Object.entries(values))
    message = message.replaceAll(`{${name}}`, String(value))
  return message
}
export function formatLocaleDate(
  value: Date | number | string,
  locale?: string,
  options?: Intl.DateTimeFormatOptions,
): string {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return String(value)
  try {
    return new Intl.DateTimeFormat(
      resolveLocale(locale),
      options ?? { dateStyle: 'medium' },
    ).format(date)
  } catch {
    return new Intl.DateTimeFormat('en', options ?? { dateStyle: 'medium' }).format(date)
  }
}
export function formatLocaleNumber(
  value: number,
  locale?: string,
  options?: Intl.NumberFormatOptions,
): string {
  try {
    return new Intl.NumberFormat(resolveLocale(locale), options).format(value)
  } catch {
    return new Intl.NumberFormat('en', options).format(value)
  }
}

